/**
 * 정리가 지우면 안 되는 그림들 (되돌릴 그림 지키기 Patch).
 *
 * ## 왜 필요한가
 *
 * 자산 정리는 **저장된 것**이 가리키는 그림만 남긴다. 그런데 되돌리기가 기억하는
 * 칸들은 저장되지 않는다 — 화면이 살아 있는 동안만 메모리에 있다. 그래서 그림
 * 하나를 갈아 끼운 뒤 몇 초가 지나면, 정리가 예전 그림을 고아로 오판해 지운다.
 * 그러고 나서 실행 취소를 누르면 **없는 그림을 가리키는 상태**로 되돌아간다.
 *
 * 조각 하나만 AI로 고치는 길이 생기면서 이 자리가 자주 지나가게 됐다 — 고칠
 * 때마다 예전 조각이 참조를 잃기 때문이다.
 *
 * 그래서 되돌릴 자리가 가리키는 그림을 여기에 걸어 둔다. 정리는 이 목록도 함께
 * 남긴다.
 *
 * ## 왜 모듈 하나인가
 *
 * 거는 쪽(작업판)과 정리하는 쪽(기획서 문서)은 서로를 모른다. 둘 다 아는 자리를
 * 만들면 한쪽이 다른 쪽을 알아야 하고, 그러면 작성기 표면에도 작업판이 딸려
 * 들어간다. 이 모듈은 **문자열 목록 하나**만 알고, 그래서 아무도 모르는 채로
 * 만난다.
 *
 * 저장하지 않는다. 새로고침하면 되돌릴 칸도 함께 사라지므로 지킬 것도 없다.
 */

let held: ReadonlySet<string> = new Set()

/**
 * 지금 지켜야 할 목록을 **통째로 바꾼다.**
 *
 * 더하는 것이 아니라 바꾸는 것이다 — 되돌릴 칸은 오래된 것부터 버려지므로,
 * 더하기만 하면 이미 버려진 칸의 그림이 영원히 남는다.
 */
export function holdAssets(ids: Iterable<string>): void {
  held = new Set(ids)
}

export function heldAssets(): string[] {
  return [...held]
}

/** 검사 이음매 — 한 검사가 걸어 둔 것이 다음 검사로 새지 않게 한다. */
export function resetAssetHoldForTests(): void {
  held = new Set()
}
