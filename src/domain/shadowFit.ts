/**
 * 이 그림에 그림자가 어울리는가 (그림자 Patch).
 *
 * 작업자가 그 자리에서 말했다: "일반 이미지 블록에 이미지를 업로드할 때 그림자가
 * 기본으로 깔리는데… 이미지 내부가 투명한 그런 이미지를 올릴 때는 그 그림자가
 * 어색해."
 *
 * ## 왜 어색한가
 *
 * 접지 그림자는 **바닥에 놓인 덩어리** 하나를 가정한다. 상자 아래에 짧고 진한
 * 타원을 깔아 "이것이 여기 닿아 있다"고 말하는 그림이다. 그 가정이 맞는 그림은
 * 병·상자·사람처럼 실루엣이 꽉 찬 것들이다.
 *
 * 로고, 글자, 테두리만 있는 프레임, 흩어진 아이콘 뭉치는 그 가정이 틀린다. 덩어리
 * 하나가 아니라 **구멍 뚫린 형태**이고, 바닥에 놓인 것도 아니다. 그런데 그림자는
 * 상자 크기만 보고 깔리므로, 글자 아래에 정체 모를 검은 타원이 생긴다.
 *
 * ## 무엇으로 가르는가
 *
 * 실루엣이 얼마나 **찼는가**로 가른다 — 불투명한 화소가 그 그림의 테두리 상자를
 * 얼마나 채우고 있는지(`ImageAnalysis.fill`). 이미 훑고 있는 화소에서 같이
 * 나오므로 다시 읽지 않는다.
 *
 *  - 사각형 사진: 1.0 — 전부 찼다
 *  - 제품 누끼(병·상자): 대개 0.5~0.8
 *  - 로고·글자·프레임: 0.1~0.35
 *
 * 이것은 **어림짐작**이지 판정이 아니다. 비스듬히 누운 가는 제품은 낮게 나오고,
 * 배경이 꽉 찬 로고는 높게 나온다. 그래서 이 값은 **처음 값**만 정하고, 사람이
 * 블록에서 바로 켜고 끌 수 있게 둔다. 어림짐작을 되돌릴 수 없게 만들면 그건
 * 어림짐작이 아니라 규칙이다.
 */

import type { ImageAnalysis } from './imageAnalysis'

/**
 * 이 아래로 비면 그림자를 끄고 시작한다.
 *
 * 0.4는 제품 누끼(대개 0.5~0.8)와 로고·글자(0.1~0.35) 사이다. 둘 다 놓치지 않는
 * 값은 없으므로, 틀렸을 때 **덜 나쁜 쪽**으로 잡았다 — 있어야 할 그림자가 꺼져
 * 있으면 켜면 그만이지만, 로고 아래 검은 타원은 그것이 왜 거기 있는지조차 모른 채
 * 결과물에 실린다.
 */
export const SHADOW_FILL_MIN = 0.4

/**
 * 이 그림에 그림자를 깔고 시작해도 되는가.
 *
 * 잰 것이 없으면(`null`) **켠다** — 지금까지의 동작이 그렇고, 못 읽었다는 이유로
 * 결과가 달라지면 사람은 무엇이 바뀌었는지 알 수 없다.
 */
export function shadowSuitsShape(analysis: ImageAnalysis | null): boolean {
  if (analysis === null) return true
  return analysis.fill >= SHADOW_FILL_MIN
}
