/**
 * 편집 오브젝트 하나 (텍스트 오브젝트 Patch §1).
 *
 * 여기 있던 픽셀 분리기(`splitTextLayer`)는 걷어냈다. 그것은 한 장에 그려진
 * 문구를 나중에 가르는 규칙이었고, 어떤 규칙을 얹어도 추측이었다 — 붙어 있는
 * 두 문구가 하나로 묶이거나 한 문구가 여럿으로 갈라졌다.
 *
 * 이제 문구도 이미지처럼 **처음부터 자기 그림 한 장**을 갖는다. 가를 일이 없고,
 * 가르는 코드도 없다. 남은 것은 "그 그림이 어느 블록의 것이고 어디에 놓이는가"
 * 라는 이름표뿐이다.
 */

import type { LayoutRect } from './imageLayout'

/** 편집 오브젝트 하나 — 기획서의 블록 하나에 대응한다. */
export interface StudioTextObject {
  /** 어느 블록에서 나온 것인가. 이 이름이 오브젝트의 정체성이다. */
  blockId: string
  /** 그 블록의 그림. 옮기고 크기를 바꿔도 이 그림은 그대로다. */
  assetId: string
  /** 페이지 좌표. 작업자가 옮기고 늘리면 이 값만 바뀐다. */
  rect: LayoutRect
  /** 앞뒤 차례. 이미지와 문구가 같은 체계의 번호를 쓴다. */
  layer: number
  /**
   * 시계 방향 기울기(도). 없으면 0 — 예전 결과는 열어도 그대로다 (회전 Patch).
   *
   * **이미 기울어져 그려진 그림을 펴 주지는 않는다.** 이 값은 우리가 더 기울이는
   * 각도이지, 그림 안의 기울기를 되돌리는 값이 아니다. 그건 다시 만들어야 한다.
   */
  angle?: number
  /**
   * **살아 있는 문구**인가 (살아 있는 문구 Patch, 2026-09-17).
   *
   * 참이면 이 그림은 AI가 만든 것이 아니라 브라우저가 글꼴·색·테두리·그림자로 그린
   * 것이고, 그 값이나 문구가 바뀌면 **저절로 다시 그려진다.** AI로 고친 문구는 이
   * 표시가 없다 — 그때부터는 그림이다. 예전 결과도 없다.
   */
  live?: true
  /**
   * 살아 있는 문구가 들어가야 할 틀. 다시 그린 그림은 이 틀 안에 가장 크게, 가운데로
   * 앉는다. 처음에는 기획서 블록 상자이고, 조각을 옮기고 늘리면 틀도 같이 움직인다 —
   * 그래서 테두리를 켰다 껐다 해도 자리가 조금씩 줄어들지 않는다.
   */
  frame?: LayoutRect
  /** 이 그림을 그릴 때 쓴 값의 지문. 지금 값과 다르면 다시 그린다. */
  liveKey?: string
  /** 그린 문구와 줄 — 기획서에 블록이 없는 조각(배너)도 다시 그릴 수 있게. */
  text?: string
  lines?: readonly string[]
}
