/**
 * 편집 오브젝트 하나 (텍스트 오브젝트 Patch §1).
 *
 * 여기 있던 픽셀 분리기(`splitTextLayer`)는 걷어냈다. 그것은 한 장에 그려진
 * 문구를 나중에 가르는 규칙이었고, 어떤 규칙을 얹어도 추측이었다 — 붙어 있는
 * 두 문구가 하나로 묶이거나 한 문구가 여럿으로 갈라졌다.
 *
 * 이제 문구도 이미지처럼 **처음부터 자기 그림 한 장**을 갖는다. 가를 일이 없고,
 * 가르는 코드도 없다. 남은 것은 "그 그림이 어느 블록의 것이고 어디에 놓이는가"
 * 라는 이름표뿐이다.
 */

import type { LayoutRect } from './imageLayout'

/** 편집 오브젝트 하나 — 기획서의 블록 하나에 대응한다. */
export interface StudioTextObject {
  /** 어느 블록에서 나온 것인가. 이 이름이 오브젝트의 정체성이다. */
  blockId: string
  /** 그 블록의 그림. 옮기고 크기를 바꿔도 이 그림은 그대로다. */
  assetId: string
  /** 페이지 좌표. 작업자가 옮기고 늘리면 이 값만 바뀐다. */
  rect: LayoutRect
  /** 앞뒤 차례. 이미지와 문구가 같은 체계의 번호를 쓴다. */
  layer: number
}
